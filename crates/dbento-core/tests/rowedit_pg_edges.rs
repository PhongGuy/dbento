use std::time::{Duration, Instant};

use crate::support::{PgFixture, edit_value, pairs, pg_fixture, rejected, row_key, val};
use dbento_core::{BatchError, Change, ChangeOutcome, EditBatch, EditValue, RowKey};

const SETUP: &str = r#"
CREATE TABLE nokey(a int, b text);
INSERT INTO nokey VALUES (1, 'x'), (2, 'y');
CREATE TABLE par(a int, b text);
CREATE TABLE kid() INHERITS (par);
BEGIN; INSERT INTO par VALUES (1, 'p'); INSERT INTO kid VALUES (1, 'k'); COMMIT;
CREATE TABLE gen(id int PRIMARY KEY, a int, g int GENERATED ALWAYS AS (a * 2) STORED,
  ia int GENERATED ALWAYS AS IDENTITY, ib int GENERATED BY DEFAULT AS IDENTITY);
INSERT INTO gen(id, a) VALUES (1, 5);
CREATE TABLE df(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, s text DEFAULT 'dflt', n int);
INSERT INTO df(s, n) VALUES ('set', 1);
CREATE TABLE ck(ts timestamptz, n numeric, s text, v int, PRIMARY KEY (ts, n, s));
INSERT INTO ck VALUES ('2024-01-02 03:04:05.123456+00', 1.50, 'it''s', 0);
"#;

async fn setup() -> PgFixture {
    let fx = pg_fixture("").await;
    fx.db.admin().await.batch_execute(SETUP).await.unwrap();
    fx
}

async fn scalar(fx: &PgFixture, sql: &str) -> String {
    fx.db.scalar(sql).await.unwrap()
}

#[tokio::test]
async fn a_table_without_a_primary_key_is_edited_by_ctid_and_xmin() {
    let fx = setup().await;
    let target = fx.target("public", "nokey").await;
    let ctid = scalar(&fx, "SELECT ctid FROM nokey WHERE a = 1").await;
    let xmin = scalar(&fx, "SELECT xmin FROM nokey WHERE a = 1").await;
    let k = || row_key(&[("ctid", val(&ctid)), ("xmin", val(&xmin))]);
    let applied = fx
        .apply_changes(
            &target,
            vec![Change::Update {
                key: k(),
                set: pairs(&[("b", val("z"))]),
            }],
        )
        .await
        .unwrap();
    applied.commit().await.unwrap();
    assert_eq!(
        scalar(&fx, "SELECT string_agg(b, ',' ORDER BY a) FROM nokey").await,
        "z,y"
    );
    // The update made a new row version, so the old locator matches nothing.
    let outcomes = rejected(
        fx.apply_changes(&target, vec![Change::Delete { key: k() }])
            .await,
    );
    assert_eq!(outcomes, vec![ChangeOutcome::Conflict]);
}

#[tokio::test]
async fn an_inheritance_parent_is_edited_with_only() {
    let fx = setup().await;
    let target = fx.target("public", "par").await;
    assert!(target.only());
    let ctid = scalar(&fx, "SELECT ctid FROM ONLY par").await;
    let xmin = scalar(&fx, "SELECT xmin FROM ONLY par").await;
    assert_eq!(
        scalar(&fx, "SELECT count(*) FROM par WHERE ctid = (SELECT ctid FROM ONLY par) AND xmin = (SELECT xmin FROM ONLY par)").await,
        "2",
        "the child row shares the parent row's locator"
    );
    let applied = fx
        .apply_changes(
            &target,
            vec![Change::Update {
                key: row_key(&[("ctid", val(&ctid)), ("xmin", val(&xmin))]),
                set: pairs(&[("b", val("q"))]),
            }],
        )
        .await
        .unwrap();
    assert_eq!(applied.affected(), 1);
    applied.commit().await.unwrap();
    assert_eq!(
        scalar(&fx, "SELECT string_agg(b, ',' ORDER BY b) FROM par").await,
        "k,q"
    );
}

#[tokio::test]
async fn generated_and_always_identity_columns_are_left_out() {
    let fx = setup().await;
    let target = fx.target("public", "gen").await;
    let applied = fx
        .apply_changes(
            &target,
            vec![
                Change::Insert {
                    values: pairs(&[
                        ("id", val("2")),
                        ("a", val("7")),
                        ("g", val("14")),
                        ("ia", val("1")),
                        ("ib", val("40")),
                    ]),
                },
                Change::Update {
                    key: row_key(&[("id", val("1"))]),
                    set: pairs(&[("a", val("6")), ("g", val("0"))]),
                },
            ],
        )
        .await
        .unwrap();
    applied.commit().await.unwrap();
    assert_eq!(
        scalar(
            &fx,
            "SELECT string_agg(concat_ws(',', id, a, g, ib), ' ' ORDER BY id) FROM gen"
        )
        .await,
        "1,6,12,1 2,7,14,40"
    );
    let only_generated = Change::Update {
        key: row_key(&[("id", val("1"))]),
        set: pairs(&[("g", val("1"))]),
    };
    assert_eq!(
        EditBatch::new(target, vec![only_generated]).unwrap_err(),
        BatchError::EmptyUpdate { change: 0 }
    );
}

#[tokio::test]
async fn default_in_updates_and_all_default_inserts() {
    let fx = setup().await;
    let target = fx.target("public", "df").await;
    let applied = fx
        .apply_changes(
            &target,
            vec![
                Change::Update {
                    key: row_key(&[("id", val("1"))]),
                    set: pairs(&[("s", EditValue::Default), ("n", EditValue::Null)]),
                },
                Change::Insert { values: vec![] },
                Change::Insert {
                    values: pairs(&[("id", EditValue::Default), ("n", val("3"))]),
                },
            ],
        )
        .await
        .unwrap();
    assert_eq!(applied.affected(), 3);
    applied.commit().await.unwrap();
    assert_eq!(
        scalar(
            &fx,
            "SELECT string_agg(concat_ws(',', id, s, n), ' ' ORDER BY id) FROM df"
        )
        .await,
        "1,dflt 2,dflt 3,dflt,3"
    );
}

#[tokio::test]
async fn a_row_locked_elsewhere_fails_after_the_lock_wait() {
    let fx = setup().await;
    let target = fx.target("public", "df").await;
    let holder = fx.db.admin().await;
    holder
        .batch_execute("BEGIN; SELECT * FROM df WHERE id = 1 FOR UPDATE")
        .await
        .unwrap();
    let started = Instant::now();
    let change = Change::Update {
        key: row_key(&[("id", val("1"))]),
        set: pairs(&[("n", val("9"))]),
    };
    let result = tokio::time::timeout(
        Duration::from_secs(20),
        fx.apply_changes(&target, vec![change]),
    )
    .await
    .expect("apply must give up on the lock by itself");
    match rejected(result).as_slice() {
        [ChangeOutcome::Failed(m)] => assert!(m.contains("lock timeout"), "{m}"),
        other => panic!("{other:?}"),
    }
    assert!(
        started.elapsed() >= Duration::from_secs(4),
        "{:?}",
        started.elapsed()
    );
    holder.batch_execute("ROLLBACK").await.unwrap();
}

#[tokio::test]
async fn a_composite_key_of_text_typed_values_matches_its_own_text() {
    let fx = setup().await;
    let target = fx.target("public", "ck").await;
    let row = fx.row("SELECT ts, n, s FROM ck").await;
    let key = ["ts", "n", "s"]
        .iter()
        .zip(&row)
        .map(|(c, v)| ((*c).to_owned(), edit_value(v)))
        .collect();
    let applied = fx
        .apply_changes(
            &target,
            vec![Change::Update {
                key: RowKey::new(key),
                set: pairs(&[("v", val("1"))]),
            }],
        )
        .await
        .unwrap();
    assert_eq!(applied.affected(), 1);
    applied.commit().await.unwrap();
    assert_eq!(scalar(&fx, "SELECT v FROM ck").await, "1");
}
