mod support;

use dbento_core::{EditTarget, Engine, IntrospectError, RelationRef, Session, SessionOptions};
use support::{pg_fixture, sqlite_fixture};

fn summary(t: &EditTarget) -> Vec<(String, String, bool)> {
    t.columns()
        .iter()
        .map(|c| (c.name().to_owned(), c.cast_type().to_owned(), c.editable()))
        .collect()
}

fn names(v: &[&str]) -> Vec<String> {
    v.iter().map(|s| (*s).to_owned()).collect()
}

async fn target(s: &mut Session, schema: &str, name: &str) -> EditTarget {
    s.edit_target(&RelationRef::new(schema, name))
        .await
        .unwrap()
}

const PG_SETUP: &str = r#"
CREATE SCHEMA "My S";
CREATE TYPE "My S"."Mood" AS ENUM ('ok', 'sad');
CREATE DOMAIN d3 AS varchar(3) CHECK (VALUE <> 'no');
CREATE DOMAIN dd3 AS d3;
CREATE TABLE sized(id int PRIMARY KEY, v varchar(3), c char(3), b bit(3), va varchar(3)[],
  ca char(3)[], ba bit(3)[], d d3, n dd3, da d3[], m "My S"."Mood", ma "My S"."Mood"[],
  g int GENERATED ALWAYS AS (id * 2) STORED, ia int GENERATED ALWAYS AS IDENTITY,
  ib int GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE "My S".multi(b text, a int, PRIMARY KEY (a, b));
CREATE TABLE nokey(a int, b text);
CREATE TABLE par(a int, b text);
CREATE TABLE kid() INHERITS (par);
CREATE TABLE parts(a int, b text) PARTITION BY RANGE (a);
CREATE TABLE parts_1 PARTITION OF parts FOR VALUES FROM (0) TO (100);
CREATE TABLE keyed_parts(a int, b text, PRIMARY KEY (a, b)) PARTITION BY RANGE (a);
CREATE TABLE keyed_parts_1 PARTITION OF keyed_parts FOR VALUES FROM (0) TO (100);
CREATE VIEW v AS SELECT * FROM sized;
"#;

#[tokio::test]
async fn postgres_columns_carry_their_catalog_cast_type_and_writability() {
    let fx = pg_fixture("").await;
    fx.db.admin().await.batch_execute(PG_SETUP).await.unwrap();
    let mut s = fx.session(SessionOptions::default()).await;
    let t = target(&mut s, "public", "sized").await;
    assert_eq!(t.engine(), Engine::Postgres);
    assert_eq!(t.relation(), &RelationRef::new("public", "sized"));
    let want = [
        ("id", "pg_catalog.int4", true),
        ("v", "pg_catalog.\"varchar\"", true),
        ("c", "pg_catalog.bpchar", true),
        ("b", "pg_catalog.\"bit\"", true),
        ("va", "pg_catalog._varchar", true),
        ("ca", "pg_catalog._bpchar", true),
        ("ba", "pg_catalog._bit", true),
        ("d", "pg_catalog.\"varchar\"", true),
        ("n", "pg_catalog.\"varchar\"", true),
        ("da", "pg_catalog._varchar", true),
        ("m", "\"My S\".\"Mood\"", true),
        ("ma", "\"My S\".\"_Mood\"", true),
        ("g", "pg_catalog.int4", false),
        ("ia", "pg_catalog.int4", false),
        ("ib", "pg_catalog.int4", true),
    ];
    assert_eq!(
        summary(&t),
        want.map(|(n, c, e)| (n.to_owned(), c.to_owned(), e))
            .to_vec()
    );
    assert_eq!(t.columns()[1].meta().type_name(), "character varying(3)");
    assert_eq!(
        t.column("ib").map(|c| c.cast_type()),
        Some("pg_catalog.int4")
    );
    assert_eq!(t.identity(), names(&["id"]).as_slice());
    assert!(t.has_identity());
    assert!(t.locators().is_empty());
    assert!(!t.only());
}

#[tokio::test]
async fn postgres_identity_is_the_key_then_ctid_and_xmin_with_only_for_parents() {
    let fx = pg_fixture("").await;
    fx.db.admin().await.batch_execute(PG_SETUP).await.unwrap();
    let mut s = fx.session(SessionOptions::default()).await;

    let multi = target(&mut s, "My S", "multi").await;
    assert_eq!(
        multi.identity(),
        names(&["a", "b"]).as_slice(),
        "key order, not column order"
    );
    assert!(multi.locators().is_empty());

    let nokey = target(&mut s, "public", "nokey").await;
    assert_eq!(nokey.identity(), names(&["ctid", "xmin"]).as_slice());
    assert_eq!(nokey.locators(), names(&["ctid", "xmin"]).as_slice());
    assert!(!nokey.only());

    let par = target(&mut s, "public", "par").await;
    assert_eq!(par.identity(), names(&["ctid", "xmin"]).as_slice());
    assert!(par.only());
    let kid = target(&mut s, "public", "kid").await;
    assert!(!kid.only());

    let parts = target(&mut s, "public", "parts").await;
    assert!(!parts.has_identity());
    assert!(parts.identity().is_empty() && parts.locators().is_empty());
    assert!(!parts.only(), "a partitioned table is never given ONLY");
    let keyed = target(&mut s, "public", "keyed_parts").await;
    assert_eq!(keyed.identity(), names(&["a", "b"]).as_slice());
    assert!(!keyed.only());

    let view = target(&mut s, "public", "v").await;
    assert!(!view.has_identity());
    assert_eq!(view.columns().len(), 15);

    let missing = s
        .edit_target(&RelationRef::new("public", "missing"))
        .await
        .unwrap_err();
    assert!(
        matches!(missing, IntrospectError::Missing { .. }),
        "{missing:?}"
    );
    assert_eq!(missing.to_string(), "no table or view public.missing");
}

const LITE_SETUP: &str = "
CREATE TABLE keyed(id INTEGER PRIMARY KEY, name TEXT DEFAULT 'x''y', n INT,
  gv INT GENERATED ALWAYS AS (n * 2) VIRTUAL, gs INT GENERATED ALWAYS AS (n * 3) STORED);
CREATE TABLE multi(b TEXT, a INT, PRIMARY KEY (a, b)) WITHOUT ROWID;
CREATE TABLE plain(a, b);
CREATE TABLE shadow1(\"RowId\" TEXT, b);
CREATE TABLE shadow2(rowid, _ROWID_, b);
CREATE TABLE shadow3(rowid, _rowid_, oid);
CREATE VIEW v AS SELECT * FROM keyed;
";

#[tokio::test]
async fn sqlite_identity_is_the_key_then_the_first_unshadowed_rowid_alias() {
    let fx = sqlite_fixture(LITE_SETUP, "");
    let mut s = fx.session(SessionOptions::default()).await;

    let keyed = target(&mut s, "main", "keyed").await;
    assert_eq!(keyed.engine(), Engine::Sqlite);
    let want = [
        ("id", "INTEGER", true),
        ("name", "TEXT", true),
        ("n", "INT", true),
        ("gv", "INT", false),
        ("gs", "INT", false),
    ];
    assert_eq!(
        summary(&keyed),
        want.map(|(n, c, e)| (n.to_owned(), c.to_owned(), e))
            .to_vec()
    );
    assert_eq!(keyed.columns()[1].meta().default(), Some("'x''y'"));
    assert_eq!(keyed.identity(), names(&["id"]).as_slice());
    assert!(keyed.locators().is_empty() && !keyed.only());

    let multi = target(&mut s, "main", "multi").await;
    assert_eq!(multi.identity(), names(&["a", "b"]).as_slice());

    // SQLite finds a table whatever the case it is named in; the target names it as stored.
    let upper = target(&mut s, "main", "KEYED").await;
    assert_eq!(upper.relation(), &RelationRef::new("main", "keyed"));
    assert_eq!(upper.identity(), names(&["id"]).as_slice());

    for (table, alias) in [
        ("plain", "rowid"),
        ("shadow1", "_rowid_"),
        ("shadow2", "oid"),
    ] {
        let t = target(&mut s, "main", table).await;
        assert_eq!(t.identity(), names(&[alias]).as_slice(), "{table}");
        assert_eq!(t.locators(), names(&[alias]).as_slice(), "{table}");
    }
    assert!(!target(&mut s, "main", "shadow3").await.has_identity());
    assert!(!target(&mut s, "main", "v").await.has_identity());

    let missing = s
        .edit_target(&RelationRef::new("main", "missing"))
        .await
        .unwrap_err();
    assert!(
        matches!(missing, IntrospectError::Missing { .. }),
        "{missing:?}"
    );
    assert_eq!(missing.to_string(), "no table or view main.missing");
    let schema = s
        .edit_target(&RelationRef::new("nope", "keyed"))
        .await
        .unwrap_err();
    assert!(
        matches!(schema, IntrospectError::Missing { .. }),
        "{schema:?}"
    );
}
